/**
 * Evaluation harness: runs quirk over every project in eval/corpora.json (public, pinned)
 * and eval/corpora.local.json (your own held-out projects; gitignored), and reports
 * findings and precision per project, so no heuristic is tuned to one codebase.
 *
 *   npm run eval                 all projects
 *   npm run eval -- bootstrap    one project
 *
 * Precision comes from eval/labels/<project>.json (eval/labels/local/<project>.json for local
 * projects, also gitignored), keyed by "<ruleId> <file>:<line>":
 *   { "bcd:api.Foo.bar src/x.js:12": { "verdict": "fp", "note": "guarded by a wrapper" } }
 * Findings without a label count as unlabelled, not as correct.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { check, type CheckResult } from '../src/engine/check.ts';
import { formatText } from '../src/cli/report.ts';
import type { Finding, Severity } from '../src/engine/finding.ts';

interface Project {
  name: string;
  repo?: string;
  rev?: string;
  local?: string;
  paths: string[];
  exclude?: string[];
  postcss?: boolean;
  heldOut?: boolean;
  why: string;
}

type Label = { verdict: 'tp' | 'fp'; note?: string };

const here = path.dirname(new URL(import.meta.url).pathname);
const repoRoot = path.resolve(here, '..');
const cacheDir = path.join(repoRoot, '.scratch', 'eval');
const resultsDir = path.join(here, 'results');

function git(cwd: string, ...args: string[]): void {
  execFileSync('git', args, { cwd, stdio: 'ignore' });
}

/** Shallow checkout of exactly the pinned commit. Files are only read, never executed. */
function checkout(project: Project): string {
  if (project.local) return path.resolve(repoRoot, project.local);
  if (!project.repo || !project.rev) throw new Error(`${project.name}: needs repo and rev, or local`);
  const dir = path.join(cacheDir, `${project.name}@${project.rev.slice(0, 12)}`);
  if (existsSync(path.join(dir, '.git'))) return dir;
  mkdirSync(dir, { recursive: true });
  git(dir, 'init', '-q');
  git(dir, 'fetch', '-q', '--depth', '1', project.repo, project.rev);
  git(dir, '-c', 'advice.detachedHead=false', 'checkout', '-q', 'FETCH_HEAD');
  return dir;
}

export const labelKey = (f: Finding, root: string) =>
  `${f.ruleId} ${path.relative(root, f.location.file)}:${f.location.line}`;

function loadLabels(project: Project): Record<string, Label> {
  const file = path.join(here, 'labels', ...(project.local ? ['local'] : []), `${project.name}.json`);
  return existsSync(file) ? (JSON.parse(readFileSync(file, 'utf8')) as Record<string, Label>) : {};
}

interface Row {
  project: Project;
  result: CheckResult;
  active: Finding[];
  bySeverity: Record<Severity, number>;
  tp: number;
  fp: number;
  unlabelled: number;
  staleLabels: number;
  top: string[];
}

async function evaluate(project: Project): Promise<Row> {
  const root = checkout(project);
  const result = await check({
    root,
    paths: project.paths,
    exclude: project.exclude,
    // Loading a PostCSS config executes the project's code: only for local, trusted projects.
    postcss: project.local && project.postcss ? 'auto' : false,
    // Evaluation measures every finding; a project's own baseline would hide them.
    baseline: false,
  });
  const active = result.findings.filter((f) => !f.suppressed);
  const labels = loadLabels(project);
  const keys = new Set(active.map((f) => labelKey(f, root)));
  let tp = 0;
  let fp = 0;
  for (const f of active) {
    const label = labels[labelKey(f, root)];
    if (label?.verdict === 'tp') tp++;
    if (label?.verdict === 'fp') fp++;
  }
  const counts = new Map<string, number>();
  for (const f of active) counts.set(f.ruleId, (counts.get(f.ruleId) ?? 0) + 1);
  mkdirSync(resultsDir, { recursive: true });
  writeFileSync(path.join(resultsDir, `${project.name}.txt`), formatText(result, root, true));
  return {
    project,
    result,
    active,
    bySeverity: {
      error: active.filter((f) => f.severity === 'error').length,
      warning: active.filter((f) => f.severity === 'warning').length,
      info: active.filter((f) => f.severity === 'info').length,
    },
    tp,
    fp,
    unlabelled: active.length - tp - fp,
    staleLabels: Object.keys(labels).filter((k) => !keys.has(k)).length,
    top: [...counts].sort((a, b) => b[1] - a[1]).slice(0, 5).map(([id, n]) => `${id.replace(/^bcd:/, '')} ×${n}`),
  };
}

function precision(row: Pick<Row, 'tp' | 'fp'>): string {
  const labelled = row.tp + row.fp;
  return labelled ? `${Math.round((row.tp / labelled) * 100)}% (${row.tp}/${labelled})` : '–';
}

function report(rows: Row[]): string {
  const lines = [
    '# quirk evaluation',
    '',
    'Generated by `npm run eval`. Do not edit by hand. Each project is pinned to a commit in',
    '`eval/corpora.json`; per-finding text reports are written to `eval/results/` (not committed).',
    'Local held-out projects (`eval/corpora.local.json`) are printed when run but never written here.',
    '',
    '| Project | Targets | Files | Errors | Warnings | Info | Suppressed | Precision (labelled) | Unlabelled |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const r of rows) {
    const name = r.project.heldOut ? `${r.project.name} (held out)` : r.project.name;
    lines.push(
      `| ${name} | ${r.result.targets.query} | ${r.result.files} | ${r.bySeverity.error} | ${r.bySeverity.warning} | ${r.bySeverity.info} | ${
        r.result.findings.length - r.active.length
      } | ${precision(r)} | ${r.unlabelled}${r.staleLabels ? ` (${r.staleLabels} stale labels)` : ''} |`,
    );
  }
  lines.push('', '## Most frequent findings', '');
  for (const r of rows) lines.push(`- **${r.project.name}**: ${r.top.join(', ') || 'none'}`);
  lines.push('', '## Why each project is here', '');
  for (const r of rows) lines.push(`- **${r.project.name}**: ${r.project.why}`);
  return `${lines.join('\n')}\n`;
}

const readProjects = (file: string): Project[] =>
  existsSync(file) ? (JSON.parse(readFileSync(file, 'utf8')) as { projects: Project[] }).projects : [];
const projects = [
  ...readProjects(path.join(here, 'corpora.json')),
  // Local projects are always held out: they measure quirk and never shape it.
  ...readProjects(path.join(here, 'corpora.local.json')).map((p) => ({ ...p, heldOut: true })),
];
const only = process.argv.slice(2);
const selected = only.length ? projects.filter((p) => only.includes(p.name)) : projects;
const rows: Row[] = [];
for (const project of selected) {
  process.stderr.write(`evaluating ${project.name}…\n`);
  rows.push(await evaluate(project));
}
// The committed report covers public projects only, so it never names a private codebase.
if (!only.length) writeFileSync(path.join(here, 'REPORT.md'), report(rows.filter((r) => !r.project.local)));
process.stdout.write(report(rows));
